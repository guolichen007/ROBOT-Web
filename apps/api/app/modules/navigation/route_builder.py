"""Right-side-coverage S-cruise geometry for the DEMO_PARKING map.

This module is the single source of truth for the demo inspection route. Both
the fresh-database seed and the existing-dev-database sync MUST call the same
builder so the two can never drift.

The robot only detects the side to its right. Every inspection pose therefore
places the parking slot in the robot's local right half-plane:

    dot(slot_center - robot_pose, vehicle_right_vector(theta)) > 0

with vehicle_right_vector(theta) = (sin(theta), -cos(theta)).

Body frame (ROS convention):

    local +X = forward
    local +Y = left
    local -Y = right

Slot codes are generated by seed.py as:

    A-01..A-09  top group 1 (x = 2.5 + col*2.15, y = 31.5)
    A-10..A-18  top group 2 (x = 27.0 + col*2.15, y = 31.5)
    A-19..A-27  column 1   (x = 5.0,  y = 3.0 + row*2.8)
    A-28..A-36  column 2   (x = 17.0, y = 3.0 + row*2.8)
    A-37..A-45  column 3   (x = 29.0, y = 3.0 + row*2.8)
    A-46..A-54  column 4   (x = 43.0, y = 3.0 + row*2.8)
"""

from __future__ import annotations

import math
from typing import NamedTuple

REMOTE_WAITING = {"x": 1.2, "y": 1.2, "theta": math.pi / 2}

_TOP_LANE_OFFSET_Y = -2.8
_COLUMN_LANE_OFFSET = 3.0
NORTH_TRANSFER_Y = 27.0  # safe east-west transfer lane north of the top row
CLEARANCE_M = 0.3


class SlotRef(NamedTuple):
    code: str
    x: float
    y: float


def slot_number(code: str) -> int:
    return int(code.rsplit("-", 1)[-1].lstrip("0") or "0")


def group_of(code: str) -> str:
    n = slot_number(code)
    if n <= 18:
        return "top"
    if n <= 27:
        return "col1"
    if n <= 36:
        return "col2"
    if n <= 45:
        return "col3"
    return "col4"


def vehicle_right_vector(theta: float) -> tuple[float, float]:
    return (math.sin(theta), -math.cos(theta))


def slot_is_on_vehicle_right(robot: dict, slot: dict) -> bool:
    rel = (slot["x"] - robot["x"], slot["y"] - robot["y"])
    right = vehicle_right_vector(robot["theta"])
    return rel[0] * right[0] + rel[1] * right[1] > 0


def inspection_pose(slot: SlotRef) -> dict:
    """Return the robot pose from which the slot is on the robot's right side."""
    group = group_of(slot.code)
    if group == "top":
        return {"x": slot.x, "y": slot.y + _TOP_LANE_OFFSET_Y, "theta": math.pi}
    if group in {"col1", "col3"}:
        return {"x": slot.x + _COLUMN_LANE_OFFSET, "y": slot.y, "theta": -math.pi / 2}
    return {"x": slot.x - _COLUMN_LANE_OFFSET, "y": slot.y, "theta": math.pi / 2}


def ordered_groups(slots: list[SlotRef]) -> list[list[SlotRef]]:
    """S-cruise order: col1 down, col2 up, col3 down, col4 up, top west."""
    col1 = sorted((s for s in slots if group_of(s.code) == "col1"), key=lambda s: -s.y)
    col2 = sorted((s for s in slots if group_of(s.code) == "col2"), key=lambda s: s.y)
    col3 = sorted((s for s in slots if group_of(s.code) == "col3"), key=lambda s: -s.y)
    col4 = sorted((s for s in slots if group_of(s.code) == "col4"), key=lambda s: s.y)
    top = sorted((s for s in slots if group_of(s.code) == "top"), key=lambda s: -s.x)
    return [col1, col2, col3, col4, top]


def ordered_codes(slots: list[SlotRef]) -> list[str]:
    return [slot.code for group in ordered_groups(slots) for slot in group]


def _dedupe(points: list[dict]) -> list[dict]:
    out: list[dict] = []
    for point in points:
        if not out or out[-1]["x"] != point["x"] or out[-1]["y"] != point["y"]:
            out.append({"x": round(point["x"], 4), "y": round(point["y"], 4)})
    return out


def build_cruise_waypoints(slots: list[SlotRef]) -> list[dict]:
    """Full waypoint list including all 54 inspection checkpoints.

    Each waypoint is ``{x, y, kind, theta?, slot_code?, sequence?}`` with
    kind in {WAITING, TRANSIT, TURN, INSPECTION}. This is what the mock robot
    executes and what the map renders.
    """
    groups = ordered_groups(slots)
    waypoints: list[dict] = [
        {"x": REMOTE_WAITING["x"], "y": REMOTE_WAITING["y"], "kind": "WAITING", "theta": REMOTE_WAITING["theta"]},
    ]

    first = inspection_pose(groups[0][0])
    # Enter the first column from the NORTH transfer lane, not by cutting
    # laterally through A-27: (1.2,1.2) -> (1.2,27.0) -> (8.0,27.0) -> A-27.
    waypoints.append({"x": REMOTE_WAITING["x"], "y": NORTH_TRANSFER_Y, "kind": "TRANSIT"})
    waypoints.append({"x": first["x"], "y": NORTH_TRANSFER_Y, "kind": "TRANSIT"})

    sequence = 0
    for group_index, group in enumerate(groups):
        for slot in group:
            sequence += 1
            pose = inspection_pose(slot)
            waypoints.append(
                {
                    "x": pose["x"],
                    "y": pose["y"],
                    "theta": pose["theta"],
                    "kind": "INSPECTION",
                    "slot_code": slot.code,
                    "sequence": sequence,
                }
            )
        if group_index == len(groups) - 1:
            continue
        end = inspection_pose(group[-1])
        nxt = inspection_pose(groups[group_index + 1][0])
        if group_index in (0, 2):
            # col1→col2 and col3→col4 exit at the bottom: transverse y=1.5.
            waypoints.append({"x": end["x"], "y": 1.5, "kind": "TURN"})
            waypoints.append({"x": nxt["x"], "y": 1.5, "kind": "TURN"})
        elif group_index == 1:
            # col2→col3 exit at the top: transverse along the north lane.
            waypoints.append({"x": end["x"], "y": NORTH_TRANSFER_Y, "kind": "TURN"})
            waypoints.append({"x": nxt["x"], "y": NORTH_TRANSFER_Y, "kind": "TURN"})
        else:
            # col4→top row: exit north onto the top inspection lane (A18).
            waypoints.append({"x": end["x"], "y": nxt["y"], "kind": "TURN"})

    top_end = inspection_pose(groups[-1][-1])
    waypoints.append({"x": REMOTE_WAITING["x"], "y": top_end["y"], "kind": "TRANSIT"})
    waypoints.append(
        {"x": REMOTE_WAITING["x"], "y": REMOTE_WAITING["y"], "kind": "WAITING", "theta": REMOTE_WAITING["theta"]}
    )
    return waypoints


def build_cruise_trajectory(slots: list[SlotRef]) -> list[dict]:
    """x/y path for the map polyline (axis-aligned lanes, no duplicates)."""
    return _dedupe([{"x": w["x"], "y": w["y"]} for w in build_cruise_waypoints(slots)])


# Safe corridor graph: vertical lanes a robot may occupy, and the two
# horizontal transfer lanes. The return planner only travels along these.
SAFE_VERTICAL_X = [1.2, 8.0, 14.0, 32.0, 40.0]
SOUTH_TRANSFER_Y = 1.0
NORTH_TRANSFER_Y = 27.0


def build_return_waypoints(current_pose: dict, full_waypoints: list[dict] | None = None, route_cursor: int | None = None) -> list[dict]:
    """Nearest safe return-to-waiting path.

    Instead of reversing the entire cruise, take the shortest corridor route:
    from the current pose drop onto the nearest vertical lane, then to the
    south transfer lane (or the north transfer lane when already up top), then
    west along the outer corridor and down to REMOTE_WAITING. This never cuts
    diagonally across parking slots.
    """
    cx = float(current_pose["x"])
    cy = float(current_pose["y"])
    waypoints: list[dict] = [{"x": cx, "y": cy, "kind": "TRANSIT"}]

    if cy > 25.4:
        # Top region: descend to the north transfer lane, then west corridor.
        waypoints.append({"x": cx, "y": NORTH_TRANSFER_Y, "kind": "TRANSIT"})
        waypoints.append({"x": REMOTE_WAITING["x"], "y": NORTH_TRANSFER_Y, "kind": "TRANSIT"})
    else:
        # Column / south region: nearest vertical lane, then south transfer.
        vx = min(SAFE_VERTICAL_X, key=lambda x: abs(x - cx))
        if abs(vx - cx) > 1e-6:
            waypoints.append({"x": vx, "y": cy, "kind": "TRANSIT"})
        waypoints.append({"x": vx, "y": SOUTH_TRANSFER_Y, "kind": "TRANSIT"})
        waypoints.append({"x": REMOTE_WAITING["x"], "y": SOUTH_TRANSFER_Y, "kind": "TRANSIT"})

    waypoints.append(
        {"x": REMOTE_WAITING["x"], "y": REMOTE_WAITING["y"], "kind": "WAITING", "theta": REMOTE_WAITING["theta"]}
    )
    return _dedupe_waypoints(waypoints)


def build_resumed_cruise_waypoints(current_pose: dict, full_waypoints: list[dict], route_cursor: int) -> list[dict]:
    """Continue a cancelled cruise from the waypoint after the cursor.

    The cursor points at the last COMPLETED inspection waypoint, so resume
    from the following waypoint and never re-run REMOTE or A-27.
    """
    next_index = min(route_cursor + 1, len(full_waypoints))
    remaining = full_waypoints[next_index:]
    head: list[dict] = [{"x": current_pose["x"], "y": current_pose["y"], "kind": "TRANSIT"}]
    if remaining and remaining[0]["x"] == head[0]["x"] and remaining[0]["y"] == head[0]["y"]:
        return remaining
    if not remaining:
        return head + [
            {"x": REMOTE_WAITING["x"], "y": REMOTE_WAITING["y"], "kind": "WAITING", "theta": REMOTE_WAITING["theta"]}
        ]
    return head + remaining


def _dedupe_waypoints(points: list[dict]) -> list[dict]:
    out: list[dict] = []
    for point in points:
        if not out or out[-1]["x"] != point["x"] or out[-1]["y"] != point["y"]:
            out.append(point)
    return out


def segment_intersects_slot(a: dict, b: dict, slot: SlotRef, half_width: float, half_height: float, margin: float) -> bool:
    """True if the segment a->b intersects the slot's expanded AABB."""
    min_x = slot.x - half_width - margin
    max_x = slot.x + half_width + margin
    min_y = slot.y - half_height - margin
    max_y = slot.y + half_height + margin

    # Segment vs AABB via slab test.
    def in_bounds(x: float, y: float) -> bool:
        return min_x <= x <= max_x and min_y <= y <= max_y

    if in_bounds(a["x"], a["y"]) or in_bounds(b["x"], b["y"]):
        return True

    # Check each edge for intersection with the segment.
    def crosses(p: tuple[float, float], q: tuple[float, float]) -> bool:
        d1 = _cross((a["x"], a["y"]), (b["x"], b["y"]), p)
        d2 = _cross((a["x"], a["y"]), (b["x"], b["y"]), q)
        d3 = _cross(p, q, (a["x"], a["y"]))
        d4 = _cross(p, q, (b["x"], b["y"]))
        if ((d1 > 0 and d2 < 0) or (d1 < 0 and d2 > 0)) and ((d3 > 0 and d4 < 0) or (d3 < 0 and d4 > 0)):
            return True
        return False

    corners = [(min_x, min_y), (max_x, min_y), (max_x, max_y), (min_x, max_y)]
    for index in range(4):
        if crosses(corners[index], corners[(index + 1) % 4]):
            return True
    return False


def _cross(o: tuple[float, float], a: tuple[float, float], b: tuple[float, float]) -> float:
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
